function Sidebar() {
  const location = useLocation();
  const navigate = useNavigate();
  const user = JSON.parse(localStorage.getItem('rr_auth') || '{}');
  const isAdmin = user.role === 'admin';
  const navItems = isAdmin ? adminNavItems : userNavItems;

  const handleLogout = () => {
    localStorage.removeItem('rr_token');
    localStorage.removeItem('rr_auth');
    navigate('/');
  };

  return (
    <aside className="w-64 h-screen bg-gray-900 border-r border-gray-800 flex flex-col p-6 fixed left-0 top-0 z-20">
      {/* Brand Header */}
      <div className="mb-8 flex items-center gap-3">
        <div className="w-10 h-10 rounded-xl bg-gradient-to-tr from-green-500 to-emerald-400 flex items-center justify-center text-gray-950 font-black text-xl shadow-lg shadow-green-500/20">
          RR
        </div>
        <div>
          <h1 className="text-white text-lg font-bold tracking-tight">Rising Roots</h1>
          <p className="text-gray-400 text-xs font-medium">{isAdmin ? 'Admin Console' : 'Member Portal'}</p>
        </div>
      </div>

      {/* Navigation */}
      <nav className="flex flex-col gap-1.5 flex-1">
        {navItems.map((item) => {
          const isActive =
            item.path === '/dashboard'
              ? location.pathname === '/dashboard'
              : location.pathname.startsWith(item.path);
          return (
            <Link
              key={item.path}
              to={item.path}
              className={`px-4 py-3 rounded-xl text-sm font-medium transition-all duration-200 flex items-center gap-3 ${
                isActive
                  ? 'bg-green-500 text-gray-950 font-semibold shadow-md shadow-green-500/10'
                  : 'text-gray-400 hover:bg-gray-800/60 hover:text-white'
              }`}
            >
              <span className={isActive ? 'text-gray-950' : 'text-gray-400'}>{item.icon}</span>
              {item.label}
            </Link>
          );
        })}
      </nav>

      {/* Role Badge */}
      <div className="bg-gray-950 border border-gray-800 p-4 rounded-xl mb-3">
        <div className="flex items-center justify-between mb-1">
          <span className="text-xs font-semibold text-gray-400">Logged in as</span>
          <span className="text-xs font-bold text-green-400 capitalize">{user.role || 'Member'}</span>
        </div>
        <p className="text-xs text-white truncate font-medium">{user.name || user.email}</p>
      </div>

      {/* Logout Button */}
      <button
        onClick={handleLogout}
        className="flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium text-gray-400 hover:bg-rose-500/10 hover:text-rose-400 transition-all cursor-pointer"
      >
        <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
        </svg>
        Log Out
      </button>
    </aside>
  );
}

export default Sidebar;